#!/usr/bin/env python
"""Generate the mechanical exercise-catalogue lists from one reviewable source.

    python tools/build_catalogue.py            # check: every generated file must be current
    python tools/build_catalogue.py --write    # regenerate the generated files

Source: config/catalogue.v1.yaml. Generated: config/selection-tax.v1.yaml,
config/variants.v1.yaml, config/templates/inference.v1.yaml, the load_basis/pairs half of
config/selection-comparability.v1.yaml, the stimulus ratings block in
config/resolver-role-quality.v1.yaml and the coverage block in docs/EXERCISE-DEMANDS.md.

The source keeps the judgement (rank order, ordinals, load basis, inference membership,
comparability pairs). The generated files keep a short header and no inline rationale; the
reasoning lives in docs/EXERCISE-VARIANTS.md and the DEC-CATALOGUE decisions.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from strength_coach.features import demands as demands_feature  # noqa: E402
from strength_coach.prescribe.demand_scope import reachable_ids  # noqa: E402
from strength_coach.utils import exercises  # noqa: E402

SOURCE = "config/catalogue.v1.yaml"
TAX = "config/selection-tax.v1.yaml"
VARIANTS = "config/variants.v1.yaml"
INFERENCE = "config/templates/inference.v1.yaml"
COMPARABILITY = "config/selection-comparability.v1.yaml"
ROLE = "config/resolver-role-quality.v1.yaml"
DEMANDS_DOC = "docs/EXERCISE-DEMANDS.md"
BEGIN = "<!-- BEGIN GENERATED DEMAND COVERAGE -->"
END = "<!-- END GENERATED DEMAND COVERAGE -->"
RATINGS_LINE = re.compile(r"^  ratings:\s*$")
RATING_ENTRY = re.compile(r"^    ([a-z0-9_]+):\s*(\d+)\s*$")

GENERATED_NOTE = "Generated by tools/build_catalogue.py --write from config/catalogue.v1.yaml."
EDIT_NOTE = "Edit that source, not this file; rationale lives in docs/EXERCISE-VARIANTS.md."

TAX_HEADER = "\n".join([
    f"# {GENERATED_NOTE}",
    f"# {EDIT_NOTE}",
    "#",
    "# Ordinal exercise-tax metadata for selection suggestions: 1 = low, 3 = high. These are",
    "# ASSUMPTIONS, not measured biomechanics; missing metadata blocks a less-taxing claim.",
    "# spinal_cost remains the safety input.",
])

VARIANTS_HEADER = "\n".join([
    f"# {GENERATED_NOTE}",
    f"# {EDIT_NOTE}",
    "#",
    "# Additional selection candidates per slot (explicit apply; the template decides the default).",
    "# Order is rank order: new candidates are appended unless the order is deliberately re-decided.",
])

INFERENCE_HEADER = "\n".join([
    f"# {GENERATED_NOTE}",
    f"# {EDIT_NOTE}",
    "#",
    "# Reconstruction inference for imported sessions: the export has no session type, so the",
    "# exercise composition is the only evidence.",
])

COMPARABILITY_HEADER = "\n".join([
    f"# {GENERATED_NOTE}",
    f"# {EDIT_NOTE}",
    "#",
    "# A = same load basis, safe to apply automatically.",
    "# B = same pattern but a changed grip/bar/ROM/stability; confirmation required.",
    "# C = different implement/load basis; never automatic.",
    "# Default is B: a configured candidate is a real variant unless its load basis differs.",
    "# Explicit pairs win over the load-basis check.",
])


def source() -> dict:
    return yaml.safe_load((ROOT / SOURCE).read_text(encoding="utf-8")) or {}


def _emit_tax(data: dict) -> str:
    lines = [TAX_HEADER, "", 'schema_version: "1.0.0"', "exercises:"]
    for exercise_id, axes in (data.get("tax") or {}).items():
        lines.append(f"  {exercise_id}:")
        for axis in ("axial", "systemic", "skill", "rom"):
            lines.append(f"    {axis}: {axes[axis]}")
    return "\n".join(lines) + "\n"


def _emit_variants(data: dict) -> str:
    lines = [VARIANTS_HEADER, "", "slots:"]
    defined: set[str] = set()
    for session, slot_map in (data.get("slots") or {}).items():
        lines.append(f"  {session}:")
        for slot, pool in slot_map.items():
            if pool in defined:
                lines.append(f"    {slot}: *{pool}")
                continue
            defined.add(pool)
            lines.append(f"    {slot}: &{pool}")
            for exercise_id in (data.get("pools") or {}).get(pool, ()):
                lines.append(f"    - {exercise_id}")
    return "\n".join(lines) + "\n"


def _emit_inference(data: dict) -> str:
    lines = [INFERENCE_HEADER, "", 'schema_version: "1.0.0"']
    for key, value in (data.get("inference") or {}).items():
        if isinstance(value, list):
            lines.append(f"{key}:")
            lines.extend(f"- {item}" for item in value)
        else:
            lines.append(f"{key}: {value}")
    return "\n".join(lines) + "\n"


def _emit_comparability(data: dict) -> str:
    lines = [COMPARABILITY_HEADER, "", 'schema_version: "1.0.0"', "default_class: B", "", "load_basis:"]
    for basis, ids in (data.get("load_basis") or {}).items():
        lines.append(f"  {basis}:")
        lines.extend(f"    - {exercise_id}" for exercise_id in ids)
    lines.extend(["", "pairs:"])
    for label, pairs in (data.get("comparability_pairs") or {}).items():
        lines.append(f"  {label}:")
        for pair in pairs:
            lines.append(f"    - [{', '.join(str(item) for item in pair)}]")
    return "\n".join(lines) + "\n"


def _shipped_demands() -> demands_feature.DemandCatalogue:
    return demands_feature.load(overlay=ROOT / "config" / "exercises" / ".no-overlay.yaml")


def derived_ratings() -> dict[str, int]:
    """Rubric: 3 = high local stimulus and compound; 2 = high and not compound, or moderate and
    compound; 1 = moderate and not compound, or low. Unknown demand means no rating at all."""
    catalogue = _shipped_demands()
    entities = exercises.taxonomy().entities
    out: dict[str, int] = {}
    for exercise_id in reachable_ids():
        level = catalogue.level(exercise_id, "local_muscular")
        compound = bool(entities.get(exercise_id, {}).get("primary_compound")
                        or entities.get(exercise_id, {}).get("main_lift"))
        if level == "high":
            out[exercise_id] = 3 if compound else 2
        elif level == "moderate":
            out[exercise_id] = 2 if compound else 1
        elif level == "low":
            out[exercise_id] = 1
    return dict(sorted(out.items()))


def coverage_block() -> str:
    catalogue = _shipped_demands()
    ids = reachable_ids()
    coverage = catalogue.coverage(ids)
    rated = coverage["rated_exercises"]
    lines = [
        BEGIN,
        "<!-- generated by tools/build_catalogue.py --write; do not hand-edit -->",
        "",
        f"Reachable ids: **{coverage['total']}** · rated on at least one dimension: **{rated}** "
        f"({100 * rated / coverage['total']:.1f} %) · reviewed {coverage['reviewed_on'] or 'never'} "
        f"· digest {coverage['digest'] or 'none'}",
        "",
        "| dimension | rated | unknown | unknown rate | supported | provisional |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for dimension, row in coverage["per_dimension"].items():
        lines.append(
            f"| {dimension} | {row['rated']} | {row['unknown']} | "
            f"{100 * row['unknown_rate']:.1f} % | {row['supported']} | {row['provisional']} |"
        )
    lines.extend(["", END])
    return "\n".join(lines)


def _restore_ratings(text: str, ratings: dict[str, int]) -> str:
    lines = text.splitlines()
    start = next((index for index, line in enumerate(lines) if RATINGS_LINE.match(line)), None)
    if start is None:
        raise SystemExit(f"{ROLE}: could not find the ratings block")
    stop = start + 1
    while stop < len(lines) and RATING_ENTRY.match(lines[stop]):
        stop += 1
    block = [f"    {exercise_id}: {rating}" for exercise_id, rating in ratings.items()]
    return "\n".join(lines[: start + 1] + block + lines[stop:]) + "\n"


def _restore_block(text: str, block: str) -> str:
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{DEMANDS_DOC}: add the BEGIN/END markers where coverage belongs")
    start = text.index(BEGIN)
    stop = text.index(END) + len(END)
    return text[:start] + block + text[stop:]


def generated() -> dict[str, str]:
    """Every generated artifact, as the exact text it should have on disk."""
    data = source()
    role_text = (ROOT / ROLE).read_text(encoding="utf-8")
    doc_text = (ROOT / DEMANDS_DOC).read_text(encoding="utf-8")
    return {
        TAX: _emit_tax(data),
        VARIANTS: _emit_variants(data),
        INFERENCE: _emit_inference(data),
        COMPARABILITY: _emit_comparability(data),
        ROLE: _restore_ratings(role_text, derived_ratings()),
        DEMANDS_DOC: _restore_block(doc_text, coverage_block()),
    }


def check() -> list[str]:
    found: list[str] = []
    for relative, text in generated().items():
        if (ROOT / relative).read_text(encoding="utf-8") != text:
            found.append(f"{relative}: generated content is stale (run tools/build_catalogue.py --write)")
    return found


def write() -> None:
    for relative, text in generated().items():
        path = ROOT / relative
        if path.read_text(encoding="utf-8") == text:
            print(f"{relative} is already current")
            continue
        path.write_text(text, encoding="utf-8")
        print(f"updated {relative}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true", help="regenerate the generated files")
    args = parser.parse_args(argv)
    if args.write:
        write()
    found = check()
    for line in found:
        print(line)
    if found:
        print(f"\n{len(found)} generated file(s) out of date")
        return 1
    print("generated catalogue files are current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
