"""The programme summary in the review must match the configuration.

The review's tables are generated by `strength_coach.prescribe.summary`; this test is the
anti-drift contract. It deliberately checks behaviour (the review names the sumo, not the old
single-leg RDL) rather than a snapshot of the whole table, while the exact block comparison
keeps the committed document current.
"""

from __future__ import annotations

from pathlib import Path

from strength_coach.prescribe import summary, templates
from strength_coach.utils import exercises

ROOT = Path(__file__).resolve().parents[1]
REVIEW = ROOT / "docs" / "STRENGTH-PROGRAM-REVIEW.md"


def test_the_review_names_the_sumo_and_not_the_replaced_lift():
    block = summary.render()
    assert "Sumo Deadlift" in block
    assert "single-leg RDL" not in block
    assert "single_leg_db_rdl" not in block


def test_the_weekly_totals_are_the_documented_cycle():
    totals = summary.weekly_sets()
    assert totals["squat (SSB main + competition support)"] == 7
    assert totals["bench (main + support)"] == 12
    assert totals["trap-bar deadlift"] == 5
    assert totals["sumo deadlift"] == 1.5
    assert totals["vertical pull"] == 4.5
    assert sum(totals.values()) == 57
    assert summary.render().count("**57 working sets/week**") == 1


def test_the_spinal_costs_match_the_cycle():
    costs = {row.session_type: row.spinal_cost for row in summary.session_rows()}
    assert costs == {"squat": 1.0, "hinge": 2.0, "bench_squat": 1.0, "bench_hinge": 2.5}
    block = summary.render()
    assert "**4** for the first week" in block
    assert "**5.5** for the second" in block


def test_every_template_exercise_has_exactly_one_display_group():
    grouped: dict[str, int] = {}
    for _label, members in summary.LIFT_GROUPS:
        for exercise_id in members:
            grouped[exercise_id] = grouped.get(exercise_id, 0) + 1
    assert all(count == 1 for count in grouped.values())
    for session_type in templates.SESSION_TYPES:
        for slot in templates.SessionTemplate.load(session_type).slots:
            exercise_id = slot.exercise or (slot.variants[0] if slot.variants else None)
            assert exercise_id is not None
            assert summary.group_for(exercise_id) is not None, exercise_id


def test_the_committed_review_block_is_current():
    text = REVIEW.read_text(encoding="utf-8")
    assert summary.extract(text) == summary.render()


def test_the_current_state_documents_do_not_use_the_old_movement():
    for relative in ("ROADMAP.md", "docs/CORE-TRAINING.md"):
        text = (ROOT / relative).read_text(encoding="utf-8")
        assert "single-leg RDL" not in text, relative
        assert "single_leg_db_rdl" not in text, relative


def test_the_block_round_trips():
    text = REVIEW.read_text(encoding="utf-8")
    block = summary.render()
    assert summary.replace(text, block) == text


def test_the_source_digest_is_stable():
    assert summary.source_digest() == summary.source_digest()
    assert summary.render() == summary.render()


def test_every_group_member_is_a_known_exercise():
    known = exercises.taxonomy().entities
    for _label, members in summary.LIFT_GROUPS:
        for exercise_id in members:
            assert exercise_id in known, exercise_id
