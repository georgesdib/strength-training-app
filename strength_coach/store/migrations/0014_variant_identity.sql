        WHEN 'Squat (partial range of motion)' THEN 'squat_partial_range_of_motion'
        WHEN 'Squat (slow downwards & upwards)' THEN 'squat_slow_downwards_and_upwards'
        WHEN 'Squat (to box)' THEN 'squat_to_box'
        WHEN 'Squat (w/bands)' THEN 'squat_w_bands'
        WHEN 'Squat (w/chains)' THEN 'squat_w_chains'
        WHEN 'Standing Single-Arm Cable Curls (Shoulder Flexed)	' THEN 'standing_single_arm_cable_curls_shoulder_flexed'
        WHEN 'Straight Arm Pulldown' THEN 'straight_arm_pulldown'
        WHEN 'Straight Bar Cable Curl' THEN 'straight_bar_cable_curl'
        WHEN 'T Bar Row' THEN 't_bar_row'
        WHEN 'Tib Bar Calves' THEN 'tib_bar_calves'
        WHEN 'Tricep Pushdown' THEN 'tricep_pushdown'
        WHEN 'Upright Row' THEN 'upright_row'
        ELSE exercise_id END
WHERE exercise_id LIKE 'pattern:%'
  AND raw_exercise NOT IN ('Competition Deadlift', 'Hyperextensions');

